import json
from collections import defaultdict

with open('/sessions/exciting-laughing-mendel/mnt/Desktop/global-travel-dashboard/data/travel_daily.json') as f:
    data = json.load(f)

dates_data = data['dates']
all_dates = sorted(dates_data.keys())

# === STEP 1: Identify all violations ===
title_dates = defaultdict(list)
for d_idx, d in enumerate(all_dates):
    items = dates_data[d]['items']
    for i_idx, item in enumerate(items):
        title_dates[item['title']].append((d, d_idx, i_idx))

violations = []
for title, occurrences in title_dates.items():
    if len(occurrences) < 4:
        continue
    runs = []
    current_run = [occurrences[0]]
    for k in range(1, len(occurrences)):
        if occurrences[k][1] == occurrences[k-1][1] + 1:
            current_run.append(occurrences[k])
        else:
            if len(current_run) >= 4:
                runs.append(current_run)
            current_run = [occurrences[k]]
    if len(current_run) >= 4:
        runs.append(current_run)
    for run in runs:
        for occ in run[3:]:
            d, d_idx, i_idx = occ
            item = dates_data[d]['items'][i_idx]
            violations.append({
                'date': d, 'item_idx': i_idx, 'title': title,
                'country': item['country'], 'category': item['category'],
                'tag': item['tag'], 'source_url': item['source_url'],
                'sub_category': item.get('sub_category', ''),
            })

print(f"Identified {len(violations)} violations")

